-- Consulta de amostras somente leitura para Firebird, versao 2 sem CTE.
-- Selecione e execute o arquivo completo; ORIGEM identifica a tabela.
-- Ate 60 registros por tabela. Nao usar a amostra para indicadores.
-- Campos vazios podem nao se aplicar ao tipo de registro.
-- Exporte o resultado completo em CSV com cabecalhos.

SELECT
    CAST('ORDENS_DE_SERVICOS' AS VARCHAR(40)) AS ORIGEM,
    CAST(OS AS VARCHAR(60)) AS REFERENCIA,
    CAST(EQUIPAMENTO AS VARCHAR(20)) AS EQUIPAMENTO,
    CAST(DATA AS TIMESTAMP) AS DATA_INICIO,
    CAST(HORA_INI AS VARCHAR(40)) AS HORA_INICIO,
    CAST(DATA_FIM AS TIMESTAMP) AS DATA_FIM,
    CAST(HORA_FIM AS VARCHAR(40)) AS HORA_FIM,
    CAST(DATA_ENCERRA AS TIMESTAMP) AS DATA_ENCERRA,
    CAST(DATA_TEM_INI AS TIMESTAMP) AS DATA_TEM_INI,
    CAST(HORA_TEM_INI AS VARCHAR(40)) AS HORA_TEM_INI,
    CAST(DATA_TEM_FIM AS TIMESTAMP) AS DATA_TEM_FIM,
    CAST(HORA_TEM_FIM AS VARCHAR(40)) AS HORA_TEM_FIM,
    CAST(HORIMETRO AS DOUBLE PRECISION) AS ODOMETRO,
    CAST(NULL AS INTEGER) AS LOTACAO,
    CAST(OS AS INTEGER) AS OS,
    CAST(NULL AS INTEGER) AS SOLICITACAO,
    CAST(ENCERRADA AS VARCHAR(20)) AS ENCERRADA,
    CAST(TIPO AS VARCHAR(20)) AS TIPO,
    CAST(NULL AS VARCHAR(200)) AS DESCRICAO,
    CAST(NULL AS VARCHAR(20)) AS FLAG,
    CAST(REABERTURA AS VARCHAR(20)) AS REABERTURA,
    CAST(PRE_LIBERACAO AS VARCHAR(20)) AS PRE_LIBERACAO,
    CAST(NUMCHAMADA AS INTEGER) AS NUMCHAMADA
FROM (SELECT FIRST 60 * FROM ORDENS_DE_SERVICOS ORDER BY DATA DESC, OS DESC) AMOSTRA_1
UNION ALL
